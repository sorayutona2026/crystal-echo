// tiny map builder: base fill, then ops: ['rect',x0,y0,x1,y1,ch] ['line',[[x,y]..],radius,ch,centreCh] ['set',x,y,ch]
function buildMap(w, h, base, ops) {
  const g = Array.from({ length: h }, () => Array(w).fill(base)), put = (x, y, c) => { if (x >= 0 && y >= 0 && x < w && y < h) g[y][x] = c; };
  for (const o of ops) {
    if (o[0] === 'rect') { for (let y = o[2]; y <= o[4]; y++) for (let x = o[1]; x <= o[3]; x++) put(x, y, o[5]); }
    else if (o[0] === 'set') put(o[1], o[2], o[3]);
    else if (o[0] === 'line') {
      const pts = o[1], r = o[2];
      for (let i = 1; i < pts.length; i++) {
        const [ax, ay] = pts[i - 1], [bx, by] = pts[i], n = Math.max(Math.abs(bx - ax), Math.abs(by - ay));
        for (let k = 0; k <= n; k++) { const cx = Math.round(ax + (bx - ax) * k / n), cy = Math.round(ay + (by - ay) * k / n); for (let dy = -r; dy <= r; dy++) for (let dx = -r; dx <= r; dx++) if (Math.abs(dx) + Math.abs(dy) <= r + (r > 0 ? 1 : 0)) put(cx + dx, cy + dy, o[3]); }
      }
      if (o[4]) for (let i = 1; i < pts.length; i++) { const [ax, ay] = pts[i - 1], [bx, by] = pts[i], n = Math.max(Math.abs(bx - ax), Math.abs(by - ay)); for (let k = 0; k <= n; k++) put(Math.round(ax + (bx - ax) * k / n), Math.round(ay + (by - ay) * k / n), o[4]); }
    }
  }
  return g.map(r => r.join(''));
}
